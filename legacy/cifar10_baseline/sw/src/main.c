/*
 * main.c
 * ARM Bare-Metal Application for CNN Accelerator on ZedBoard
 * 
 * This runs on the Cortex-A9 PS and controls:
 *   1. Loading CNN weights into DDR
 *   2. Receiving images from laptop via UART
 *   3. Sending images to FPGA accelerator via AXI
 *   4. Reading results and sending back to laptop
 *   5. Benchmarking FPGA vs CPU inference
 * 
 * Build with: Vitis SDK (create bare-metal application)
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "xparameters.h"
#include "xil_cache.h"
#include "xil_printf.h"
#include "xtime_l.h"

// HLS-generated driver (auto-created when you export from Vivado)
#include "xcnn_top.h"

// ============================================================
// CNN Dimensions (must match HLS defines)
// ============================================================
#define IMG_CH       3
#define IMG_H        32
#define IMG_W        32
#define NUM_CLASSES  10

#define INPUT_SIZE    (IMG_CH * IMG_H * IMG_W)
#define CONV1_W_SIZE  (16 * 3 * 3 * 3)
#define CONV1_B_SIZE  16
#define CONV2_W_SIZE  (32 * 16 * 3 * 3)
#define CONV2_B_SIZE  32
#define FC_W_SIZE     (NUM_CLASSES * 32 * 6 * 6)
#define FC_B_SIZE     NUM_CLASSES
#define OUTPUT_SIZE   NUM_CLASSES

// ============================================================
// Fixed-point conversion helpers
// ============================================================
// ap_fixed<16,6> has 10 fractional bits
#define FRAC_BITS 10
#define FLOAT_TO_FIXED(f) ((int16_t)((f) * (1 << FRAC_BITS)))
#define FIXED_TO_FLOAT(x) ((float)(x) / (float)(1 << FRAC_BITS))

// ============================================================
// Memory-mapped addresses for data buffers in DDR
// ============================================================
#define DDR_BASE        0x10000000
#define INPUT_ADDR      (DDR_BASE + 0x00000000)
#define CONV1_W_ADDR    (DDR_BASE + 0x00100000)
#define CONV1_B_ADDR    (DDR_BASE + 0x00200000)
#define CONV2_W_ADDR    (DDR_BASE + 0x00300000)
#define CONV2_B_ADDR    (DDR_BASE + 0x00400000)
#define FC_W_ADDR       (DDR_BASE + 0x00500000)
#define FC_B_ADDR       (DDR_BASE + 0x00600000)
#define OUTPUT_ADDR     (DDR_BASE + 0x00700000)

// ============================================================
// Include pre-trained weights (generated by training script)
// ============================================================
#include "weights.h"

// ============================================================
// HLS Accelerator Instance
// ============================================================
XCnn_top cnn_instance;

// ============================================================
// Initialize FPGA Accelerator
// ============================================================
int init_accelerator() {
    int status;

    XCnn_top_Config *cfg = XCnn_top_LookupConfig(XPAR_CNN_TOP_0_DEVICE_ID);
    if (!cfg) {
        xil_printf("[ERROR] Could not find CNN accelerator config\r\n");
        return -1;
    }

    status = XCnn_top_CfgInitialize(&cnn_instance, cfg);
    if (status != XST_SUCCESS) {
        xil_printf("[ERROR] CNN accelerator init failed: %d\r\n", status);
        return -1;
    }

    xil_printf("[INFO] CNN accelerator initialized successfully\r\n");
    return 0;
}

// ============================================================
// Load Weights to DDR
// ============================================================
void load_weights() {
    xil_printf("[INFO] Loading CNN weights to DDR...\r\n");

    int16_t *conv1_w = (int16_t *)CONV1_W_ADDR;
    int16_t *conv1_b = (int16_t *)CONV1_B_ADDR;
    int16_t *conv2_w = (int16_t *)CONV2_W_ADDR;
    int16_t *conv2_b = (int16_t *)CONV2_B_ADDR;
    int16_t *fc_w    = (int16_t *)FC_W_ADDR;
    int16_t *fc_b    = (int16_t *)FC_B_ADDR;

    // Copy from header arrays to DDR
    for (int i = 0; i < CONV1_W_SIZE; i++)
        conv1_w[i] = FLOAT_TO_FIXED(conv1_weights_float[i]);

    for (int i = 0; i < CONV1_B_SIZE; i++)
        conv1_b[i] = FLOAT_TO_FIXED(conv1_bias_float[i]);

    for (int i = 0; i < CONV2_W_SIZE; i++)
        conv2_w[i] = FLOAT_TO_FIXED(conv2_weights_float[i]);

    for (int i = 0; i < CONV2_B_SIZE; i++)
        conv2_b[i] = FLOAT_TO_FIXED(conv2_bias_float[i]);

    for (int i = 0; i < FC_W_SIZE; i++)
        fc_w[i] = FLOAT_TO_FIXED(fc_weights_float[i]);

    for (int i = 0; i < FC_B_SIZE; i++)
        fc_b[i] = FLOAT_TO_FIXED(fc_bias_float[i]);

    // Flush cache to ensure DDR has the data
    Xil_DCacheFlush();
    xil_printf("[INFO] Weights loaded successfully\r\n");
}

// ============================================================
// Run FPGA Inference
// ============================================================
float run_fpga_inference(int16_t *input_data, int *predicted_class) {
    XTime start, end;
    float elapsed_ms;

    // Set accelerator arguments (DDR addresses)
    XCnn_top_Set_input_r(&cnn_instance, (u64)INPUT_ADDR);
    XCnn_top_Set_conv1_weights(&cnn_instance, (u64)CONV1_W_ADDR);
    XCnn_top_Set_conv1_bias(&cnn_instance, (u64)CONV1_B_ADDR);
    XCnn_top_Set_conv2_weights(&cnn_instance, (u64)CONV2_W_ADDR);
    XCnn_top_Set_conv2_bias(&cnn_instance, (u64)CONV2_B_ADDR);
    XCnn_top_Set_fc_weights(&cnn_instance, (u64)FC_W_ADDR);
    XCnn_top_Set_fc_bias(&cnn_instance, (u64)FC_B_ADDR);
    XCnn_top_Set_output_r(&cnn_instance, (u64)OUTPUT_ADDR);

    // Flush input data from cache to DDR
    Xil_DCacheFlushRange((UINTPTR)INPUT_ADDR, INPUT_SIZE * sizeof(int16_t));

    // Start timer
    XTime_GetTime(&start);

    // Start accelerator
    XCnn_top_Start(&cnn_instance);

    // Wait for completion
    while (!XCnn_top_IsDone(&cnn_instance));

    // Stop timer
    XTime_GetTime(&end);

    // Invalidate cache to read fresh output from DDR
    Xil_DCacheInvalidateRange((UINTPTR)OUTPUT_ADDR, OUTPUT_SIZE * sizeof(int16_t));

    // Find predicted class
    int16_t *output = (int16_t *)OUTPUT_ADDR;
    int max_idx = 0;
    int16_t max_val = output[0];
    for (int i = 1; i < NUM_CLASSES; i++) {
        if (output[i] > max_val) {
            max_val = output[i];
            max_idx = i;
        }
    }
    *predicted_class = max_idx;

    // Calculate elapsed time in milliseconds
    // COUNTS_PER_SECOND is defined by Xilinx BSP (typically 333MHz / 2)
    elapsed_ms = 1000.0f * (float)(end - start) / (float)(COUNTS_PER_SECOND);

    return elapsed_ms;
}

// ============================================================
// CPU-Only Inference (for comparison)
// ============================================================
float run_cpu_inference(int16_t *input_data, int *predicted_class) {
    XTime start, end;

    // Intermediate buffers
    static float f_input[IMG_CH][IMG_H][IMG_W];
    static float conv1_out[16][30][30];
    static float pool1_out[16][15][15];
    static float conv2_out[32][13][13];
    static float pool2_out[32][6][6];
    static float fc_out[NUM_CLASSES];

    XTime_GetTime(&start);

    // Convert input to float
    int idx = 0;
    for (int c = 0; c < IMG_CH; c++)
        for (int h = 0; h < IMG_H; h++)
            for (int w = 0; w < IMG_W; w++)
                f_input[c][h][w] = FIXED_TO_FLOAT(input_data[idx++]);

    // Conv Layer 1 + ReLU
    for (int oc = 0; oc < 16; oc++)
        for (int oh = 0; oh < 30; oh++)
            for (int ow = 0; ow < 30; ow++) {
                float sum = conv1_bias_float[oc];
                for (int ic = 0; ic < 3; ic++)
                    for (int kh = 0; kh < 3; kh++)
                        for (int kw = 0; kw < 3; kw++)
                            sum += f_input[ic][oh+kh][ow+kw]
                                 * conv1_weights_float[oc*3*3*3 + ic*3*3 + kh*3 + kw];
                conv1_out[oc][oh][ow] = (sum > 0) ? sum : 0;
            }

    // MaxPool 1
    for (int c = 0; c < 16; c++)
        for (int h = 0; h < 15; h++)
            for (int w = 0; w < 15; w++) {
                float m = conv1_out[c][2*h][2*w];
                if (conv1_out[c][2*h][2*w+1] > m) m = conv1_out[c][2*h][2*w+1];
                if (conv1_out[c][2*h+1][2*w] > m) m = conv1_out[c][2*h+1][2*w];
                if (conv1_out[c][2*h+1][2*w+1] > m) m = conv1_out[c][2*h+1][2*w+1];
                pool1_out[c][h][w] = m;
            }

    // Conv Layer 2 + ReLU
    for (int oc = 0; oc < 32; oc++)
        for (int oh = 0; oh < 13; oh++)
            for (int ow = 0; ow < 13; ow++) {
                float sum = conv2_bias_float[oc];
                for (int ic = 0; ic < 16; ic++)
                    for (int kh = 0; kh < 3; kh++)
                        for (int kw = 0; kw < 3; kw++)
                            sum += pool1_out[ic][oh+kh][ow+kw]
                                 * conv2_weights_float[oc*16*3*3 + ic*3*3 + kh*3 + kw];
                conv2_out[oc][oh][ow] = (sum > 0) ? sum : 0;
            }

    // MaxPool 2
    for (int c = 0; c < 32; c++)
        for (int h = 0; h < 6; h++)
            for (int w = 0; w < 6; w++) {
                float m = conv2_out[c][2*h][2*w];
                if (conv2_out[c][2*h][2*w+1] > m) m = conv2_out[c][2*h][2*w+1];
                if (conv2_out[c][2*h+1][2*w] > m) m = conv2_out[c][2*h+1][2*w];
                if (conv2_out[c][2*h+1][2*w+1] > m) m = conv2_out[c][2*h+1][2*w+1];
                pool2_out[c][h][w] = m;
            }

    // FC Layer
    for (int cls = 0; cls < NUM_CLASSES; cls++) {
        float sum = fc_bias_float[cls];
        int fc_idx = 0;
        for (int c = 0; c < 32; c++)
            for (int h = 0; h < 6; h++)
                for (int w = 0; w < 6; w++) {
                    sum += pool2_out[c][h][w]
                         * fc_weights_float[cls * 1152 + fc_idx];
                    fc_idx++;
                }
        fc_out[cls] = sum;
    }

    XTime_GetTime(&end);

    // Find predicted class
    int max_idx = 0;
    float max_val = fc_out[0];
    for (int i = 1; i < NUM_CLASSES; i++) {
        if (fc_out[i] > max_val) {
            max_val = fc_out[i];
            max_idx = i;
        }
    }
    *predicted_class = max_idx;

    float elapsed_ms = 1000.0f * (float)(end - start) / (float)(COUNTS_PER_SECOND);
    return elapsed_ms;
}

// ============================================================
// Main Application
// ============================================================
int main() {
    xil_printf("\r\n");
    xil_printf("==============================================\r\n");
    xil_printf("  ZedBoard CNN Accelerator Demo\r\n");
    xil_printf("  Real-Time Object Detection\r\n");
    xil_printf("==============================================\r\n\r\n");

    // Initialize
    if (init_accelerator() != 0) return -1;
    load_weights();

    // Prepare test input (gradient pattern for now — replaced by camera data later)
    int16_t *input_buf = (int16_t *)INPUT_ADDR;
    for (int i = 0; i < INPUT_SIZE; i++) {
        input_buf[i] = FLOAT_TO_FIXED(0.01f * i);
    }

    // ---- Benchmark: FPGA Inference ----
    xil_printf("\r\n--- FPGA Accelerated Inference ---\r\n");
    int fpga_class;
    float fpga_total = 0;
    int num_runs = 100;

    for (int run = 0; run < num_runs; run++) {
        float latency = run_fpga_inference(input_buf, &fpga_class);
        fpga_total += latency;
    }
    float fpga_avg = fpga_total / num_runs;

    xil_printf("  Predicted class : %d\r\n", fpga_class);
    xil_printf("  Avg latency     : ");
    // Print float manually since xil_printf doesn't support %f
    xil_printf("%d.%02d ms\r\n", (int)fpga_avg, (int)(fpga_avg * 100) % 100);
    xil_printf("  FPS             : ");
    float fpga_fps = 1000.0f / fpga_avg;
    xil_printf("%d.%d\r\n", (int)fpga_fps, (int)(fpga_fps * 10) % 10);

    // ---- Benchmark: CPU-Only Inference ----
    xil_printf("\r\n--- CPU-Only Inference (ARM Cortex-A9) ---\r\n");
    int cpu_class;
    float cpu_total = 0;

    for (int run = 0; run < num_runs; run++) {
        float latency = run_cpu_inference(input_buf, &cpu_class);
        cpu_total += latency;
    }
    float cpu_avg = cpu_total / num_runs;

    xil_printf("  Predicted class : %d\r\n", cpu_class);
    xil_printf("  Avg latency     : ");
    xil_printf("%d.%02d ms\r\n", (int)cpu_avg, (int)(cpu_avg * 100) % 100);
    xil_printf("  FPS             : ");
    float cpu_fps = 1000.0f / cpu_avg;
    xil_printf("%d.%d\r\n", (int)cpu_fps, (int)(cpu_fps * 10) % 10);

    // ---- Comparison ----
    float speedup = cpu_avg / fpga_avg;
    xil_printf("\r\n--- Performance Comparison ---\r\n");
    xil_printf("  Speedup (CPU/FPGA): ");
    xil_printf("%d.%dx\r\n", (int)speedup, (int)(speedup * 10) % 10);

    if (speedup >= 2.0f) {
        xil_printf("  [PASS] Meets 2x speedup requirement!\r\n");
    } else {
        xil_printf("  [WARN] Below 2x target. Optimization needed.\r\n");
    }

    xil_printf("\r\n==============================================\r\n");
    xil_printf("  Demo Complete!\r\n");
    xil_printf("==============================================\r\n");

    return 0;
}
