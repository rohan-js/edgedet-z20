#ifndef EDGEDET_ADDRESS_MAP_H
#define EDGEDET_ADDRESS_MAP_H

#define EDZ_ACCEL_BASE_ADDRESS 0x43C00000U
#define EDZ_DMA_BASE_ADDRESS 0x40400000U
#define EDZ_INPUT_BUFFER_ADDRESS 0x10000000U
#define EDZ_INPUT_BUFFER_CAPACITY 0x00064000U /* 51,200 padded AXIS words = 409,600 */
#define EDZ_OUTPUT_BUFFER_ADDRESS 0x10100000U
#define EDZ_OUTPUT_BUFFER_CAPACITY 0x00002AF8U /* 5,500 int16 = 11,000 */

#if (EDZ_INPUT_BUFFER_ADDRESS + EDZ_INPUT_BUFFER_CAPACITY > EDZ_OUTPUT_BUFFER_ADDRESS)
#error "EdgeDet DDR buffers overlap"
#endif

#endif
